--------------------------------------------------------------------------------
-- 0) DROP (best-effort)
--------------------------------------------------------------------------------
declare
  procedure safe(p_sql varchar2, p_ignore number) is
  begin
    execute immediate p_sql;
  exception
    when others then
      if sqlcode != p_ignore then raise; end if;
  end;
begin
  -- packages
  safe('drop package ai_nl2sql', -4043);
  safe('drop package ai_sql_exec', -4043);
  safe('drop package ai_sql_guard', -4043);
  safe('drop package ai_log', -4043);

  -- views (AI first)
  safe('drop view ai_v_sales_order_lines', -942);
  safe('drop view ai_v_sales_order_daily', -942);
  safe('drop view v_sales_orders', -942);
  safe('drop view v_sales_customers', -942);

  -- infra tables
  safe('drop table ai_nl2sql_whitelist purge', -942);
  safe('drop table ai_nl2sql_log purge', -942);

  -- domain tables (children first)
  safe('drop table sales_order_lines purge', -942);
  safe('drop table sales_orders purge', -942);
  safe('drop table sales_products purge', -942);
  safe('drop table sales_customers purge', -942);

  -- lookups
  safe('drop table sales_lu_product_category purge', -942);
  safe('drop table sales_lu_currency purge', -942);
  safe('drop table sales_lu_order_status purge', -942);
  safe('drop table sales_lu_country purge', -942);
  safe('drop table sales_lu_segment purge', -942);
end;
/

