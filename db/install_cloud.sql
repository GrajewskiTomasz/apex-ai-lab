create table SALES_CUSTOMERS (
  customer_id   number generated by default as identity primary key,
  customer_code varchar2(30) not null,
  customer_name varchar2(200) not null,
  segment_code  varchar2(30) not null,
  city          varchar2(200),
  country_code  varchar2(2) not null,
  created_at    date not null,
  is_active     char(1) default 'Y' not null,
  constraint SALES_CUSTOMERS_U1 unique (customer_code),
  constraint SALES_CUSTOMERS_CK1 check (is_active in ('Y','N')),
  constraint SALES_CUSTOMERS_FK1 foreign key (segment_code) references SALES_LU_SEGMENT(segment_code),
  constraint SALES_CUSTOMERS_FK2 foreign key (country_code) references SALES_LU_COUNTRY(country_code)
);

create table SALES_PRODUCTS (
  product_id    number generated by default as identity primary key,
  sku           varchar2(60) not null,
  product_name  varchar2(200) not null,
  category_code varchar2(30) not null,
  is_active     char(1) default 'Y' not null,
  constraint SALES_PRODUCTS_U1 unique (sku),
  constraint SALES_PRODUCTS_CK1 check (is_active in ('Y','N')),
  constraint SALES_PRODUCTS_FK1 foreign key (category_code) references SALES_LU_PRODUCT_CATEGORY(category_code)
);

create table SALES_ORDERS (
  order_id       number generated by default as identity primary key,
  order_no       varchar2(40) not null,
  customer_id    number not null,
  created_at     date not null,
  closed_at      date,
  status_code    varchar2(20) not null,
  currency_code  varchar2(3) not null,
  notes          varchar2(2000),
  constraint SALES_ORDERS_U1 unique (order_no),
  constraint SALES_ORDERS_FK1 foreign key (customer_id) references SALES_CUSTOMERS(customer_id),
  constraint SALES_ORDERS_FK2 foreign key (status_code) references SALES_LU_ORDER_STATUS(status_code),
  constraint SALES_ORDERS_FK3 foreign key (currency_code) references SALES_LU_CURRENCY(currency_code)
);

create table SALES_ORDER_LINES (
  line_id         number generated by default as identity primary key,
  order_id        number not null,
  product_id      number not null,
  qty             number(12,3) not null,
  unit_price_net  number(12,2) not null,
  tax_rate        number(5,4) not null,
  amount_net      number(12,2) not null,
  amount_gross    number(12,2) not null,
  constraint SALES_ORDER_LINES_FK1 foreign key (order_id) references SALES_ORDERS(order_id),
  constraint SALES_ORDER_LINES_FK2 foreign key (product_id) references SALES_PRODUCTS(product_id),
  constraint SALES_ORDER_LINES_CK1 check (qty > 0),
  constraint SALES_ORDER_LINES_CK2 check (unit_price_net >= 0),
  constraint SALES_ORDER_LINES_CK3 check (tax_rate between 0 and 1),
  constraint SALES_ORDER_LINES_CK4 check (amount_net >= 0),
  constraint SALES_ORDER_LINES_CK5 check (amount_gross >= 0)
);

create index SALES_ORDERS_I1 on SALES_ORDERS(customer_id);
create index SALES_ORDERS_I2 on SALES_ORDERS(status_code);
create index SALES_ORDERS_I3 on SALES_ORDERS(currency_code);
create index SALES_ORDER_LINES_I1 on SALES_ORDER_LINES(order_id);
create index SALES_ORDER_LINES_I2 on SALES_ORDER_LINES(product_id);

