prompt === 2) Seed whitelist entries (based on SALES seed views) ===
merge into AI_NL2SQL_WHITELIST t
using (
  select 'AI_V_SALES_ORDER_LINES' view_name, 'Y' enabled_yn,
         'Pozycje zamowien z klientem i produktem (najczesciej do analiz i filtrow).' purpose
  from dual
  union all
  select 'AI_V_SALES_ORDER_DAILY', 'Y',
         'Agregacja dzienna per status i waluta (szybkie wykresy i trendy).' purpose
  from dual
) s
on (t.view_name = s.view_name)
when matched then
  update set t.enabled_yn = s.enabled_yn, t.purpose = s.purpose
when not matched then
  insert (view_name, enabled_yn, purpose)
  values (s.view_name, s.enabled_yn, s.purpose);

commit;

